import { createContext, useContext, useState, type ReactNode } from "react";

export type IncidentType = "Crowd Density" | "Weapon Detection" | "Person of Interest" | "Medical" | "Lost Person";
export type IncidentStatus = "New" | "Acknowledged" | "Under Review" | "Resolved";
export type Severity = "Low" | "Medium" | "High" | "Critical";

export interface Camera {
  id: string;
  name: string;
  zone: string;
  status: "Online" | "Degraded" | "Offline";
  peopleCount: number;
  x: number; // map position in %
  y: number;
}

export interface Incident {
  id: string;
  type: IncidentType;
  zone: string;
  cameraId: string;
  severity: Severity;
  status: IncidentStatus;
  time: string; // ISO
  note: string;
  x: number;
  y: number;
}

