interface Store {
  cameras: Camera[];
  incidents: Incident[];
  thresholds: { warning: number; critical: number };
  setThresholds: (t: { warning: number; critical: number }) => void;
  simulateCrowdAlert: (cameraId?: string) => Incident;
  setStatus: (id: string, status: IncidentStatus) => void;
}

const Ctx = createContext<Store | null>(null);

export function DemoStoreProvider({ children }: { children: ReactNode }) {
  const [cameras] = useState(initialCameras);
  const [incidents, setIncidents] = useState(initialIncidents);
  const [thresholds, setThresholds] = useState({ warning: 1500, critical: 2200 });

  const simulateCrowdAlert = (cameraId?: string) => {
    const cam = cameras.find((c) => c.id === cameraId) ?? cameras[Math.floor(Math.random() * cameras.length)]!;
    const num = 1000 + incidents.length + 1;
    const inc: Incident = {
      id: `INC-${num}`,
      type: "Crowd Density",
      zone: cam.zone,
      cameraId: cam.id,
      severity: Math.random() > 0.5 ? "Critical" : "High",
      status: "New",
      time: new Date().toISOString(),
      note: "SIMULATED alert generated by operator for demonstration.",
      x: cam.x + (Math.random() * 8 - 4),
      y: cam.y + (Math.random() * 8 - 4),
    };
    setIncidents((prev) => [inc, ...prev]);
    return inc;
  };

  const setStatus = (id: string, status: IncidentStatus) =>
    setIncidents((prev) => prev.map((i) => (i.id === id ? { ...i, status } : i)));

  return (
    <Ctx.Provider value={{ cameras, incidents, thresholds, setThresholds, simulateCrowdAlert, setStatus }}>
      {children}
    </Ctx.Provider>
  );
}

export function useDemoStore() {
  const s = useContext(Ctx);
  if (!s) throw new Error("useDemoStore must be used inside DemoStoreProvider");
  return s;
}

